<?php

namespace App\Http\Controllers\Salary;

use App\Http\Controllers\Controller;
use App\Models\SalaryPeriod;
use App\Models\SalaryRecord;
use App\Models\SalaryVoucher;
use App\Support\PrintQrCode;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Database\QueryException;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Inertia\Inertia;

class SalaryVoucherController extends Controller
{
    public function __construct()
    {
        $this->setAbilities([]);
    }

    public function index(Request $request)
    {
        $this->authorize('read-salary-vouchers');

        $filters = $request->all('search');

        $vouchers = SalaryVoucher::query()
            ->whereNull('parent_id') // list view shows bulk masters + standalone individuals, not bulk children
            ->with(['period:id,label,batch_reference', 'staff:id,name'])
            ->when($filters['search'] ?? null, fn ($q, $s) => $q->where('voucher_number', 'like', "%{$s}%"))
            ->orderByDesc('id')
            ->paginate()
            ->withQueryString();

        return Inertia::render('Salary/Vouchers/Index', [
            'filters' => $filters,
            'vouchers' => $vouchers->through(fn (SalaryVoucher $v) => [
                'id' => $v->id,
                'voucher_number' => $v->voucher_number,
                'type' => $v->type,
                'period_label' => optional($v->period)->label,
                'staff_name' => optional($v->staff)->name,
                'net_salary' => (float) $v->net_salary,
                'current_payment' => (float) $v->current_payment,
                'payment_date' => optional($v->payment_date)->format('Y-m-d'),
            ]),
        ]);
    }

    public function generateIndividual(Request $request, $recordId)
    {
        $this->authorize('create-salary-vouchers');

        $record = SalaryRecord::with(['staff', 'period'])->findOrFail($recordId);

        $existing = SalaryVoucher::where('type', SalaryVoucher::TYPE_INDIVIDUAL)
            ->where('salary_period_id', $record->salary_period_id)
            ->where('staff_id', $record->staff_id)
            ->first();

        if ($existing) {
            return redirect()->route('salary.vouchers.show', $existing->id);
        }

        $voucher = $this->snapshotVoucher($record, SalaryVoucher::TYPE_INDIVIDUAL, null, $request->user()->id);

        log_activity(__('Salary voucher generated.'), ['voucher_number' => $voucher->voucher_number], $voucher, 'Salary');

        \App\Services\SalaryNotifier::fire('vouchers_generated', $voucher, $request->user(), __('Salary Voucher Generated'), 'Salary voucher ' . $voucher->voucher_number . ' for ' . optional($record->staff)->name . ' (' . optional($record->period)->label . ') was generated by ' . $request->user()->name . '.', ['reference' => $voucher->voucher_number, 'period' => optional($record->period)->label, 'batch' => optional($record->period)->batch_reference], $record->staff);

        return redirect()->route('salary.vouchers.show', $voucher->id)->with('message', __('Salary voucher generated.'));
    }

    public function generateBulk(Request $request, $periodId)
    {
        $this->authorize('create-salary-vouchers');

        $period = SalaryPeriod::findOrFail($periodId);
        $records = $period->records()->with(['staff', 'period'])->get();
        abort_if($records->isEmpty(), 422, 'This period has no salary records to voucher.');

        $master = DB::transaction(function () use ($period, $records, $request) {
            $master = SalaryVoucher::create([
                'voucher_number' => $this->nextReference(),
                'type' => SalaryVoucher::TYPE_BULK,
                'salary_period_id' => $period->id,
                'gross_amount' => round($records->sum('total_earnings'), 2),
                'total_deductions' => round($records->sum('total_deductions'), 2),
                'net_salary' => round($records->sum('net_salary'), 2),
                'opening_outstanding_balance' => round($records->sum('opening_outstanding_balance'), 2),
                'current_payment' => round($records->sum('current_payable'), 2),
                'remaining_balance' => round($records->sum(fn (SalaryRecord $r) => $r->remainingBalance()), 2),
                'prepared_by_user_id' => $request->user()->id,
            ]);

            foreach ($records as $record) {
                $existing = SalaryVoucher::where('type', SalaryVoucher::TYPE_INDIVIDUAL)
                    ->where('salary_period_id', $period->id)
                    ->where('staff_id', $record->staff_id)
                    ->exists();

                if (! $existing) {
                    $this->snapshotVoucher($record, SalaryVoucher::TYPE_INDIVIDUAL, $master->id, $request->user()->id);
                }
            }

            return $master;
        });

        log_activity(__('Bulk salary voucher generated.'), ['voucher_number' => $master->voucher_number, 'count' => $records->count()], $master, 'Salary');

        \App\Services\SalaryNotifier::fire('vouchers_generated', $master, $request->user(), __('Salary Vouchers Generated'), 'Bulk salary voucher ' . $master->voucher_number . ' for ' . $records->count() . ' employee(s) was generated by ' . $request->user()->name . '.', ['reference' => $master->voucher_number, 'period' => optional($master->period)->label, 'batch' => optional($master->period)->batch_reference]);

        return redirect()->route('salary.vouchers.show', $master->id)->with('message', __('Bulk salary voucher generated for :count employee(s).', ['count' => $records->count()]));
    }

    public function show(Request $request, $id)
    {
        $this->authorize('read-salary-vouchers');

        $voucher = SalaryVoucher::with(['period:id,label,batch_reference', 'staff:id,name,staff_number,position', 'children.staff:id,name,staff_number'])->findOrFail($id);

        return Inertia::render('Salary/Vouchers/Show', ['voucher' => $this->presentDetail($voucher)]);
    }

    public function print(Request $request, $id)
    {
        $this->authorize('print-salary-vouchers');

        $voucher = SalaryVoucher::with(['period', 'staff', 'children.staff'])->findOrFail($id);
        $this->recordPrint($voucher);

        return view('salary.voucher-print', $this->printData($voucher, false));
    }

    public function pdf(Request $request, $id)
    {
        $this->authorize('print-salary-vouchers');

        $voucher = SalaryVoucher::with(['period', 'staff', 'children.staff'])->findOrFail($id);
        $this->recordPrint($voucher);

        return Pdf::loadView('salary.voucher-print', $this->printData($voucher, true))
            ->setPaper('a4')
            ->download($voucher->voucher_number . '.pdf');
    }

    private function recordPrint(SalaryVoucher $voucher): void
    {
        $voucher->increment('printed_count');
        if (! $voucher->first_printed_at) {
            $voucher->update(['first_printed_at' => now()]);
        }
    }

    private function snapshotVoucher(SalaryRecord $record, string $type, ?int $parentId, int $userId): SalaryVoucher
    {
        return SalaryVoucher::create([
            'voucher_number' => $this->nextReference(),
            'type' => $type,
            'salary_period_id' => $record->salary_period_id,
            'staff_id' => $record->staff_id,
            'parent_id' => $parentId,
            'gross_amount' => $record->total_earnings,
            'total_deductions' => $record->total_deductions,
            'net_salary' => $record->net_salary,
            'opening_outstanding_balance' => $record->opening_outstanding_balance,
            'current_payment' => $record->current_payable,
            'remaining_balance' => $record->remainingBalance(),
            'prepared_by_user_id' => $userId,
        ]);
    }

    private function nextReference(): string
    {
        $prefix = 'SV-' . now()->format('Y') . '-';
        $prefixLength = strlen($prefix) + 1;

        for ($attempt = 0; $attempt < 3; $attempt++) {
            $maxSuffix = (int) DB::table('salary_vouchers')
                ->selectRaw("MAX(CAST(SUBSTRING(voucher_number, {$prefixLength}) AS UNSIGNED)) as max_suffix")
                ->where('voucher_number', 'like', "{$prefix}%")
                ->value('max_suffix');
            $candidate = $prefix . str_pad((string) ($maxSuffix + 1), 6, '0', STR_PAD_LEFT);

            if (! SalaryVoucher::where('voucher_number', $candidate)->exists()) {
                return $candidate;
            }
        }

        abort(500, 'Unable to generate a unique salary voucher number.');
    }

    private function printData(SalaryVoucher $voucher, bool $isPdf): array
    {
        return [
            'voucher' => $this->presentDetail($voucher),
            'companyName' => \App\Models\PaymentVoucher::COMPANY_NAME,
            'qr' => PrintQrCode::dataUri(route('salary.vouchers.show', $voucher->id)),
            'isPdf' => $isPdf,
            'signatures' => app(\App\Services\Signatories\SignatureResolver::class)->resolve('salary_voucher', $voucher),
        ];
    }

    private function presentDetail(SalaryVoucher $voucher): array
    {
        return [
            'id' => $voucher->id,
            'voucher_number' => $voucher->voucher_number,
            'type' => $voucher->type,
            'period_label' => optional($voucher->period)->label,
            'staff_name' => optional($voucher->staff)->name,
            'staff_number' => optional($voucher->staff)->staff_number,
            'gross_amount' => (float) $voucher->gross_amount,
            'total_deductions' => (float) $voucher->total_deductions,
            'net_salary' => (float) $voucher->net_salary,
            'opening_outstanding_balance' => (float) $voucher->opening_outstanding_balance,
            'current_payment' => (float) $voucher->current_payment,
            'remaining_balance' => (float) $voucher->remaining_balance,
            'prepared_by_name' => optional($voucher->preparedBy)->name,
            'approved_by_name' => optional($voucher->approvedBy)->name,
            'paid_by_name' => optional($voucher->paidBy)->name,
            'payment_date' => optional($voucher->payment_date)->format('Y-m-d'),
            'payment_method' => $voucher->payment_method,
            'payment_reference' => $voucher->payment_reference,
            'printed_count' => $voucher->printed_count,
            'created_at' => optional($voucher->created_at)->format('Y-m-d H:i'),
            'children' => $voucher->relationLoaded('children') ? $voucher->children->map(fn (SalaryVoucher $c) => [
                'id' => $c->id,
                'voucher_number' => $c->voucher_number,
                'staff_name' => optional($c->staff)->name,
                'net_salary' => (float) $c->net_salary,
            ])->values() : [],
        ];
    }
}
