<template>
  <div class="ct-trail" :class="{ 'is-wide': wide }">
    <div class="ct-row">
      <span class="ct-k">{{ $t('Prepared by') }}</span>
      <span class="ct-v">{{ checkin.user ? checkin.user.name : '-' }}</span>
      <span class="ct-d">{{ checkin.created_at ? $datetime(checkin.created_at) : '-' }}</span>
    </div>

    <div class="ct-row">
      <span class="ct-k">{{ $t('Approved by') }}</span>
      <template v-if="status === 'Approved'">
        <span v-if="approvedBySystem" class="ct-v ct-sys lg-tip tip-left" :data-tip="$t('Approved by WIMS System')" tabindex="0">{{ $t('WIMS Admin') }}</span>
        <span v-else class="ct-v">{{ checkin.approver ? checkin.approver.name : '-' }}<span v-if="checkin.approved_by_role" class="ct-role">{{ checkin.approved_by_role }}</span></span>
        <span class="ct-d">{{ checkin.approved_at ? $datetime(checkin.approved_at) : '-' }}</span>
      </template>
      <template v-else-if="status === 'Rejected'">
        <span class="ct-v ct-bad">{{ $t('Rejected') }}<template v-if="checkin.rejecter"> {{ $t('by') }} {{ checkin.rejecter.name }}</template></span>
        <span class="ct-d">{{ checkin.rejected_at ? $datetime(checkin.rejected_at) : '-' }}</span>
        <span v-if="checkin.rejection_reason" class="ct-note">{{ checkin.rejection_reason }}</span>
      </template>
      <span v-else-if="status === 'Pending'" class="ct-v ct-wait">{{ $t('Waiting for approval') }}</span>
      <span v-else class="ct-v ct-none">-</span>
    </div>

    <div class="ct-row">
      <span class="ct-k">{{ $t('GRN generated by') }}</span>
      <template v-if="checkin.grn_number && status === 'Approved'">
        <span class="ct-v">
          <span class="ct-grn">{{ checkin.grn_number }}</span>
          <span v-if="grnBySystem" class="ct-sys lg-tip tip-left" :data-tip="$t('Generated by WIMS System')" tabindex="0">{{ $t('WIMS Admin') }}</span>
          <template v-else>{{ checkin.grn_generator ? checkin.grn_generator.name : '-' }}</template>
        </span>
        <span class="ct-d">{{ checkin.grn_generated_at ? $datetime(checkin.grn_generated_at) : '-' }}</span>
      </template>
      <span v-else class="ct-v ct-none">{{ status === 'Pending' ? $t('Generated when approved') : '-' }}</span>
    </div>
  </div>
</template>

<script>
// The three steps of a check-in: who prepared it and when, who approved it and when, who generated its Goods Received Note and when.
// A check-in completed before approvals existed shows "WIMS Admin" with a tooltip saying the WIMS System did it.
export default {
  props: { checkin: { type: Object, required: true }, wide: { type: Boolean, default: false } },
  computed: {
    // rows cached offline before approvals existed only carry the draft flag
    status() {
      return this.checkin.status || (this.checkin.draft == 1 ? 'Draft' : 'Approved');
    },
    // nobody approved / generated it: it was completed before approvals existed (the full record does not carry the flags, so they are worked out here too)
    approvedBySystem() {
      return this.checkin.approved_by_system ?? !this.checkin.approved_by;
    },
    grnBySystem() {
      return this.checkin.grn_by_system ?? !this.checkin.grn_generated_by;
    },
  },
};
</script>

