<script>
import AdminLayout from '@/Layouts/AdminLayout.vue';
import PageHeader from '@/Shared/Page/PageHeader.vue';

export default {
  components: { AdminLayout, PageHeader },

  props: {
    warehouse: { type: Object, default: null },
    aggregate: { type: Boolean, default: false },
    managedBy: { type: Array, default: () => [] },
    items: { type: Array, default: () => [] },
    checkins: { type: Array, default: () => [] },
    checkouts: { type: Array, default: () => [] },
    transfers: { type: Array, default: () => [] },
  },

  data() {
    return {
      itemSearch: '',
      itemSort: null,
      itemSortDirection: 'asc',
    };
  },

  computed: {
    filteredItems() {
      const term = this.itemSearch.trim().toLowerCase();
      if (!term) {
        return this.items;
      }

      return this.items.filter(item => {
        return [item.code, item.name, item.warehouse, item.unit]
          .some(field => (field ?? '').toString().toLowerCase().includes(term));
      });
    },

    sortedItems() {
      if (!this.itemSort) {
        return this.filteredItems;
      }

      const column = this.itemSort;
      const direction = this.itemSortDirection === 'asc' ? 1 : -1;

      return [...this.filteredItems].sort((a, b) => {
        let valueA = a[column];
        let valueB = b[column];

        if (column === 'quantity') {
          valueA = Number(valueA) || 0;
          valueB = Number(valueB) || 0;
        } else {
          valueA = (valueA ?? '').toString().toLowerCase();
          valueB = (valueB ?? '').toString().toLowerCase();
        }

        if (valueA < valueB) return -1 * direction;
        if (valueA > valueB) return 1 * direction;
        return 0;
      });
    },

    hasRecentTransactionsOnlyView() {
      const roles = this.$page?.props?.auth?.user?.roles || [];
      return roles.some((role) => [
        'Procurement Manager',
        'Procurement Manger',
        'Store Manager',
        'Store Manger',
      ].includes(role.name));
    },

    currentUserName() {
      return this.$page?.props?.auth?.user?.name || this.$page?.props?.auth?.user?.email || this.$t('Unknown');
    },

    generatedDate() {
      return new Date().toLocaleString();
    },

    appName() {
      return this.$page?.props?.settings?.app_name || 'RANS Workflow Integrated Management System';
    },

    versionLabel() {
      return this.$page?.props?.settings?.version_label || 'v1.6';
    },

    footerCredit() {
      return this.$page?.props?.settings?.footer_credit || 'Developed by Extrion';
    },

    statTiles() {
      return [
        { icon: 'bag', tone: 'sky', label: this.$t('Items'), value: this.items.length },
        { icon: 'in', tone: 'teal', label: this.$t('Checkins'), value: this.checkins.length },
        { icon: 'out', tone: 'indigo', label: this.$t('Checkouts'), value: this.checkouts.length },
        { icon: 'truck', tone: 'violet', label: this.$t('Transfers'), value: this.transfers.length },
      ];
    },

    sections() {
      return [
        { title: this.$t('Checkins'), icon: 'in', tone: 'teal', rows: this.checkins, showRoute: 'checkins.show', relationLabel: this.$t('Contact') },
        { title: this.$t('Checkouts'), icon: 'out', tone: 'indigo', rows: this.checkouts, showRoute: 'checkouts.show', relationLabel: this.$t('Contact') },
        { title: this.$t('Transfers'), icon: 'truck', tone: 'violet', rows: this.transfers, showRoute: 'transfers.show', relationLabel: this.$t('Route') },
      ];
    },
  },

  methods: {
    print() {
      window.print();
    },

    initials(name) {
      return (name || '?').toString().trim().split(/\s+/).slice(0, 2).map(w => w.charAt(0).toUpperCase()).join('');
    },

    goItem(id) {
      this.$inertia.visit(route('items.show', id));
    },

    setItemSort(column) {
      if (this.itemSort === column) {
        this.itemSortDirection = this.itemSortDirection === 'asc' ? 'desc' : 'asc';
      } else {
        this.itemSort = column;
        this.itemSortDirection = 'asc';
      }
    },

    itemSortIndicator(column) {
      if (this.itemSort !== column) {
        return '';
      }

      return this.itemSortDirection === 'asc' ? '▲' : '▼';
    },
  },
};
</script>

