<template>
  <admin-layout :title="$t('x_report', { x: $t('Checkout') })">
    <div class="lg-page px-4 md:px-0 rc-form">
      <page-header
        icon="out"
        :title="$t('x_report', { x: $t('Checkout') })"
        :subtitle="$t('Transactions are displayed based on the filters you select below.')"
      >
        <button type="button" class="lg-btn lg-btn-soft" :aria-pressed="showForm ? 'true' : 'false'" @click="toggleForm()">
          <icons name="toggle" class="w-4 h-4" />
          <span class="hidden sm:inline">{{ $t('toggle_x', { x: $t('Form') }) }}</span>
        </button>
      </page-header>

      <div class="lg-note lg-note-blue rc-generated">
        <icons name="clock" class="w-4 h-4" />
        <div class="rc-generated-body">
          <span><strong>{{ $t('Report Generated Date') }}:</strong> {{ new Date().toLocaleString() }}</span>
          <span><strong>{{ $t('Generated By') }}:</strong> {{ ($page.props.auth && $page.props.auth.user && $page.props.auth.user.name) || 'N/A' }}</span>
        </div>
      </div>

      <stat-tiles :items="statTiles" />

      <transition name="slidedown">
        <div v-show="showForm" class="w-full print:hidden rc-filters">
          <section class="lg-card">
            <header class="lg-card-head">
              <span class="lg-card-ico lg-ico-sky"><icons name="filter" class="w-5 h-5" /></span>
              <div class="min-w-0 flex-1">
                <h2 class="lg-card-title">{{ $t('Filters') }}</h2>
                <p class="lg-card-sub">{{ $t('Transactions are displayed based on the filters you select below.') }}</p>
              </div>
            </header>
            <report-form
              type="checkout"
              :users="users"
              :contacts="contacts"
              :categories="categories"
              :warehouses="warehouses"
              :listing="listing"
              :action="route('reports.checkout')"
            />
          </section>
        </div>
      </transition>

      <div class="rc-toolbar print:hidden">
        <div class="rc-search">
          <icons name="search" class="w-4 h-4 rc-search-ico" />
          <input
            v-model="search"
            @input="queueSearch"
            @keyup.enter="runSearch"
            type="text"
            class="rc-search-input"
            :placeholder="$t('Search')"
          />
        </div>
        <div class="rc-toolbar-btns">
          <button type="button" class="lg-btn lg-btn-dark" @click="openPrint"><icons name="printer" class="w-4 h-4" />{{ $t('Print') }}</button>
          <button type="button" class="lg-btn lg-btn-red" @click="downloadPdf"><icons name="download" class="w-4 h-4" />{{ $t('Download PDF') }}</button>
        </div>
