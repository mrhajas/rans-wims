<script>
import Modal from '@/Jetstream/Modal.vue';
import PageHeader from '@/Shared/Page/PageHeader.vue';
import StatTiles from '@/Shared/Page/StatTiles.vue';
import ReportForm from '@/Pages/Report/Form.vue';
import Pagination from '@/Shared/Pagination.vue';
import AdminLayout from '@/Layouts/AdminLayout.vue';
import CheckoutDetails from '@/Pages/Checkout/Details.vue';
import EmailReportButton from '@/Shared/EmailReportButton.vue';

export default {
  components: {
    Modal,
    PageHeader,
    StatTiles,
    ReportForm,
    Pagination,
    AdminLayout,
    CheckoutDetails,
    EmailReportButton,
  },

  props: {
    filters: Object,
    checkouts: Object,
    contacts: Array,
    users: Array,
    categories: Array,
    warehouses: Array,
    listing: Array,
  },

  data() {
    return {
      checkout: null,
      details: false,
      showForm: true,
      loading: false,
      search: this.filters.search || '',
      searchTimer: null,
    };
  },

  beforeUnmount() {
    if (this.searchTimer) {
      clearTimeout(this.searchTimer);
    }
  },

  computed: {
    statTiles() {
      const list = this.checkouts || {};
      const rows = list.data || [];
      const total = list.meta && list.meta.total != null ? list.meta.total : rows.length;

      return [
        { icon: 'out', tone: 'indigo', label: this.$t('Total Records'), value: total },
        { icon: 'list', tone: 'sky', label: this.$t('On this page'), value: rows.length },
        { icon: 'doc-text', tone: 'amber', label: this.$t('Draft'), value: rows.filter(r => r.draft == 1).length },
      ];
    },
    canEditCheckouts() {
      const user = this.$page.props.auth?.user;
      const roleNames = (user?.roles || []).map(role => role.name);

      return this.$can('update-checkouts') || roleNames.includes('Super Admin') || roleNames.includes('Admin') || Boolean(user?.edit_all);
    },
  },

  methods: {
    goToEdit(id) {
      window.location.assign(route('checkouts.edit', id));
    },
    queueSearch() {
      if (this.searchTimer) {
        clearTimeout(this.searchTimer);
      }

      this.searchTimer = setTimeout(() => {
        this.runSearch();
      }, 350);
    },
    currentFilters(output = null) {
      const params = { ...this.filters, search: this.search || undefined };
      if (!params.search) {
        delete params.search;
      }
      if (output) {
        params.output = output;
      }
      return params;
    },
    runSearch() {
      this.$inertia.get(this.route('reports.checkout', this.currentFilters()), {}, { preserveState: true, replace: true });
    },
    openPrint() {
      window.open(this.route('reports.checkout', this.currentFilters('print')), '_blank');
    },
    downloadPdf() {
      window.open(this.route('reports.checkout', this.currentFilters('pdf')), '_blank');
    },
    toggleForm() {
      this.showForm = !this.showForm;
    },
    goto(id) {
      if (this.checkout && this.checkout.id == id) {
        this.details = true;
      } else {
        this.loading = true;
        axios.get(route('checkouts.show', id) + '?json=yes').then(res => {
          this.checkout = res.data;
          this.details = true;
          this.loading = false;
        });
      }
    },
    showDetails() {
      this.details = false;
    },
    hideDetails() {
      this.details = false;
    },
    print() {
      window.print();
    },
  },
};
</script>

