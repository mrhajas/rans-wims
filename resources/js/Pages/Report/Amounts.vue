  <admin-layout :title="$t('x_report', { x: $t('Warehouse Stock Value') })">
    <div class="lg-page px-4 md:px-0">
      <page-header
        icon="chart-pie"
        :title="$t('x_report', { x: $t('Warehouse Stock Value') })"
        :subtitle="$t('View stock value in each warehouse')"
      >
        <button type="button" @click="openPrint" class="lg-btn lg-btn-primary">
          <icons name="printer" class="w-4 h-4" />{{ $t('Print') }}
        </button>
        <button type="button" @click="downloadPdf" class="lg-btn lg-btn-dark">
          <icons name="down" class="w-4 h-4" />{{ $t('Download PDF') }}
        </button>
      </page-header>

      <stat-tiles :items="statTiles" />

      <p class="ra-meta">
        <strong>{{ $t('Report Generated Date') }}:</strong> {{ $datetime(now) }}
        &nbsp;&middot;&nbsp;
        <strong>{{ $t('Generated By') }}:</strong> {{ ($page.props.auth && $page.props.auth.user && $page.props.auth.user.name) || 'N/A' }}
      </p>

      <!-- Category tabs — softcoded off whatever warehouse "status"
           (Project(s) / Warehouse(s) Type) values exist in the data, plus an
           "Uncategorized" bucket; "View All" leads and is the default.
           Selecting a tab re-scopes the stat tiles, chart and table. -->
      <div class="ra-tabs print:hidden">
        <div class="ra-tabs-scroll">
          <button
            type="button"
            class="ra-tab"
            :class="{ 'ra-tab-active': activeCategory === null }"
            @click="activeCategory = null"
          >
            <icons name="table" class="w-3.5 h-3.5" />
            {{ $t('View All') }}
            <span class="ra-tab-count">{{ listing.length }}</span>
          </button>
          <button
            v-for="cat in categories"
            :key="cat.key"
            type="button"
            class="ra-tab"
            :class="{ 'ra-tab-active': activeCategory === cat.key }"
            @click="activeCategory = cat.key"
          >
            <span class="ra-tab-dot" :style="{ background: cat.color }"></span>
            {{ cat.key }}
            <span class="ra-tab-count">{{ cat.count }}</span>
          </button>
        </div>
      </div>

      <section class="lg-card print:hidden">
        <header class="lg-card-head">
          <span class="lg-card-ico lg-ico-teal"><icons name="chart-bar" class="w-5 h-5" /></span>
          <div class="min-w-0 flex-1">
            <h2 class="lg-card-title">{{ $t('Stock Value by Warehouse') }}</h2>
          </div>
          <span v-if="activeCategory" class="lg-chip lg-chip-cyan" style="text-transform: none">{{ activeCategory }}</span>
        </header>
        <div class="ra-chart">
          <vue-highcharts type="chart" :options="chartOptions" :redrawOnUpdate="true" :oneToOneUpdate="false" :animateOnUpdate="true" style="min-width: 420px" />
        </div>
      </section>

      <section class="lg-card">
        <header class="lg-card-head ra-head">
          <span class="lg-card-ico lg-ico-sky"><icons name="building" class="w-5 h-5" /></span>
          <div class="min-w-0 flex-1">
            <h2 class="lg-card-title">{{ $t('Project(s) / Warehouse(s) Name') }}</h2>
          </div>
          <div class="ra-search print:hidden">
            <icons name="search" class="ra-search-icon" />
            <input v-model="search" type="text" class="ra-search-input" :placeholder="$t('Search warehouse..')" />
          </div>
        </header>

        <div class="lg-table-wrap">
          <table class="lg-table lg-responsive">
            <thead>
              <tr>
                <th>{{ $t('SN') }}</th>
                <th>{{ $t('Project(s) / Warehouse(s) Name') }}</th>
                <th>{{ $t('Share') }}</th>
                <th class="num">{{ $t('Stock Value') }}</th>
              </tr>
            </thead>
            <tbody>
              <tr
                :key="ci"
                v-for="(item, ci) in visibleItems"
                class="ra-row-in"
                :style="{ animationDelay: Math.min(ci * 25, 500) + 'ms' }"
              >
                <td :data-label="$t('SN')" class="ra-faint">{{ ci + 1 }}</td>
                <td :data-label="$t('Project(s) / Warehouse(s) Name')">
                  <Link :href="route('reports.warehousestock', { warehouseId: item.id })" class="ra-wh-link lg-main">
                    <span class="ra-wh-dot" :style="{ background: dotColor(ci) }"></span>
                    {{ item.name }}
                  </Link>
                </td>
                <td :data-label="$t('Share')" class="ra-share-cell">
                  <div class="ra-share">
                    <div class="ra-share-track">
                      <div class="ra-share-fill" :style="{ width: shareWidth(item.amount) + '%', background: dotColor(ci) }"></div>
                    </div>
                    <span class="ra-share-pct">{{ shareWidth(item.amount) }}%</span>
                  </div>
                </td>
                <td :data-label="$t('Stock Value')" class="num ra-strong">{{ formatPrice(item.amount) }} Tsh</td>
              </tr>
              <tr v-if="filteredItems.length === 0" class="lg-empty-row">
                <td class="lg-empty" colspan="4">{{ $t('There is no data to display.') }}</td>
              </tr>
              <tr v-if="filteredItems.length > 1" class="ra-foot">
                <td data-label=""></td>
                <td :data-label="$t('Total')">{{ $t('Total') }}</td>
                <td data-label=""></td>
                <td :data-label="$t('Stock Value')" class="num">{{ formatPrice(filteredTotal) }} Tsh</td>
              </tr>
            </tbody>
          </table>
        </div>

        <!-- Show All / Collapse — only the browse view (no active search) is
             truncated to rowLimit. -->
        <div v-if="hasMoreThanLimit" class="flex justify-center mt-4 print:hidden">
          <button type="button" class="lg-btn lg-btn-soft" @click="expanded = !expanded">
            <icons :name="expanded ? 'up' : 'down'" class="w-3.5 h-3.5" />
            {{ expanded ? $t('Collapse') : $t('Show All') + ' (' + filteredItems.length + ')' }}
          </button>
        </div>
      </section>
    </div>
  </admin-layout>
