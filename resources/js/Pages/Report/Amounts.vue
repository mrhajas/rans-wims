<script>
import VueHighcharts from 'vue3-highcharts';
import AdminLayout from '@/Layouts/AdminLayout.vue';
import PageHeader from '@/Shared/Page/PageHeader.vue';
import StatTiles from '@/Shared/Page/StatTiles.vue';
import SelectInput from '@/Shared/SelectInput.vue';
import TextInput from '@/Shared/TextInput.vue';
import TecButton from '@/Jetstream/Button.vue';

const PALETTE = ['#0891b2', '#4f46e5', '#d97706', '#059669', '#db2777', '#7c3aed', '#0284c7', '#dc2626'];

export default {
  components: {
    AdminLayout,
    PageHeader,
    StatTiles,
    SelectInput,
    TextInput,
    TecButton,
    VueHighcharts,
  },

  props: {
    listing: Array,
  },

  data() {
    return {
      search: '',
      activeCategory: null,
      expanded: false,
      rowLimit: 10,
      now: new Date(),
      animated: { value: 0, count: 0 },
    };
  },

  mounted() {
    this.animateStats();
  },

  watch: {
    activeCategory() {
      this.animateStats();
      this.expanded = false;
    },
  },

  computed: {
    // Softcoded from whatever `category` values are actually present on
    // the listing (see ReportController::warehouseamounts, sourced from the
    // warehouse's own "status"/Type field) — never a fixed hardcoded list,
    // so a new type shows up here on its own the moment a warehouse uses it.
    categories() {
      const counts = new Map();
      this.listing.forEach(item => {
        const key = item.category || 'Uncategorized';
        counts.set(key, (counts.get(key) || 0) + 1);
      });
      return [...counts.entries()]
        .sort((a, b) => b[1] - a[1])
        .map(([key, count], index) => ({ key, count, color: PALETTE[index % PALETTE.length] }));
    },
    categoryFilteredItems() {
      const items = this.activeCategory ? this.listing.filter(item => (item.category || 'Uncategorized') === this.activeCategory) : this.listing;
      return [...items].sort((a, b) => Number(b.amount || 0) - Number(a.amount || 0));
    },
    statTiles() {
      return [
        { icon: 'chart-pie', tone: 'emerald', label: this.$t('Company Total Value'), value: 'Tsh ' + this.formatPrice(this.animated.value) },
        { icon: 'building', tone: 'sky', label: this.$t('Warehouses Listed'), value: Math.round(this.animated.count) },
        { icon: 'chip', tone: 'amber', label: this.$t('Top Warehouse'), value: this.topWarehouse ? this.topWarehouse.name : '-' },
      ];
    },
    filteredTotal() {
      return this.filteredItems.reduce((sum, item) => sum + Number(item.amount || 0), 0);
    },
    totalValue() {
      return this.categoryFilteredItems.reduce((sum, item) => sum + Number(item.amount || 0), 0);
    },
    topWarehouse() {
      return this.categoryFilteredItems.length ? this.categoryFilteredItems[0] : null;
    },
    filteredItems() {
      const query = this.search.toLowerCase();
      if (query === '') {
        return this.categoryFilteredItems;
      }
      return this.categoryFilteredItems.filter(row => Object.values(row).some(item => String(item).toLowerCase().includes(query)));
    },
    // Only truncate the browse view (no active search) — a search result is
    // already a deliberately narrowed list, so every match should show.
    visibleItems() {
      if (this.search.trim() !== '' || this.expanded) {
        return this.filteredItems;
      }
      return this.filteredItems.slice(0, this.rowLimit);
    },
    hasMoreThanLimit() {
      return this.search.trim() === '' && this.filteredItems.length > this.rowLimit;
    },
    chartOptions() {
      const sorted = this.categoryFilteredItems.slice(0, 12);
      const vm = this;
      return {
        chart: {
          type: 'bar',
          spacingTop: 10,
          style: { fontFamily: 'Nunito' },
          height: Math.max(220, sorted.length * 34),
        },
        credits: { enabled: false },
        title: { text: undefined },
        colors: PALETTE,
        xAxis: {
          categories: sorted.map(w => w.name),
          labels: { style: { fontSize: '11px' } },
        },
        yAxis: {
          min: 0,
          title: { text: undefined },
          labels: {
            formatter() {
              return vm.formatCompact(this.value);
            },
          },
        },
        legend: { enabled: false },
        tooltip: {
          shadow: false,
          useHTML: true,
          borderRadius: 8,
          borderColor: '#1F2937',
          style: { color: '#fff' },
          backgroundColor: '#1F2937',
          formatter() {
            return `<div style="min-width:150px"><div style="font-weight:700;margin-bottom:2px">${this.point.category}</div><div>Tsh ${vm.formatPrice(this.point.y)}</div></div>`;
          },
        },
        plotOptions: {
          series: {
            animation: { duration: 900 },
            colorByPoint: true,
            borderRadius: 4,
            dataLabels: {
              enabled: true,
              formatter() {
                return vm.formatCompact(this.y);
              },
              style: { fontSize: '10px', fontWeight: '600', textOutline: 'none', color: '#475569' },
            },
          },
        },
        series: [{ name: this.$t('Stock Value'), data: sorted.map(w => Number(w.amount || 0)) }],
      };
    },
  },

  methods: {
    openPrint() {
      window.open(this.route('reports.warehouseamounts', { output: 'print' }), '_blank');
    },
    downloadPdf() {
      window.open(this.route('reports.warehouseamounts', { output: 'pdf' }), '_blank');
    },
    formatPrice(value) {
      return new Intl.NumberFormat('en-US', { style: 'decimal', minimumFractionDigits: 2 }).format(value);
    },
    formatCompact(value) {
      return new Intl.NumberFormat('en-US', { notation: 'compact', maximumFractionDigits: 1 }).format(Number(value) || 0);
    },
    shareWidth(amount) {
      if (!this.totalValue) {
        return 0;
      }
      return Math.round((Number(amount) / this.totalValue) * 1000) / 10;
    },
    dotColor(index) {
      return PALETTE[index % PALETTE.length];
    },
    // Delta-time-independent ease-out count-up (same shape used on the
    // Warehouse Stock report) — replays whenever the active category tab
    // changes, so switching tabs visibly "populates" the new scope.
    animateNumber(key, target, duration = 900) {
      const start = this.animated[key] || 0;
      const startTime = performance.now();
      const step = now => {
        const progress = Math.min((now - startTime) / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        this.animated[key] = start + (target - start) * eased;
        if (progress < 1) {
          requestAnimationFrame(step);
        } else {
          this.animated[key] = target;
        }
      };
      requestAnimationFrame(step);
    },
    animateStats() {
      this.animateNumber('value', this.totalValue);
      this.animateNumber('count', this.categoryFilteredItems.length);
    },
  },
};
</script>

