<template>
  <admin-layout :title="$t('x_report', { x: $t('Warehouse Stock') })">
    <div class="lg-page px-4 md:px-0 stk-shell">
      <offline-report-notice v-if="$connection.status === 'offline'" class="mb-6 relative z-[1]" />

      <page-header
        icon="building"
        :title="$t('x_report', { x: $t('Warehouse Stock') })"
        :subtitle="$t('Entire available stock in') + ' ' + (selectedWarehouseName || $t('a project / warehouse'))"
      >
        <button type="button" class="lg-btn lg-btn-dark" :disabled="!warehouse" @click="openPrint">
          <icons name="printer" class="w-4 h-4" />{{ $t('Print') }}
        </button>
        <button type="button" class="lg-btn lg-btn-red" :disabled="!warehouse" @click="downloadPdf">
          <icons name="download" class="w-4 h-4" />{{ $t('Download PDF') }}
        </button>
      </page-header>

      <!-- Stat tiles count up from 0 whenever the underlying warehouse
           (and therefore stocklist) changes. -->
      <stat-tiles :items="statTiles" />

      <section class="lg-card stk-filters print:hidden">
        <header class="lg-card-head">
          <span class="lg-card-ico lg-ico-sky"><icons name="filter" class="w-5 h-5" /></span>
          <div class="min-w-0 flex-1">
            <h2 class="lg-card-title">{{ $t('Filters') }}</h2>
            <p class="lg-card-sub">{{ $t('Search Item') }} / {{ $t('Select Warehouse / Project') }}</p>
          </div>
        </header>
        <div class="lg-fields">
          <div class="stk-field">
            <label class="stk-field-label">
              <icons name="search" class="w-3.5 h-3.5 inline-flex mr-1" />{{ $t('Search Item') }}
            </label>
            <div class="stk-input-wrap">
              <icons name="search" class="stk-input-icon" />
              <text-input v-model="search" class="stk-search-field" :placeholder="$t('Search by item name or code…')" />
            </div>
          </div>
          <div class="stk-field">
            <label class="stk-field-label">
              <icons name="building" class="w-3.5 h-3.5 inline-flex mr-1" />{{ $t('Select Warehouse / Project') }}
            </label>
            <div class="stk-input-wrap">
              <icons name="building" class="stk-input-icon" />
              <auto-complete
                :suggestions="warehouses"
                v-model="warehouse"
                @update:model-value="onWarehouseChange"
                :placeholder="$t('Select Warehouse / Project')"
                class="stk-warehouse-field w-full"
              />
            </div>
          </div>
        </div>
      </section>

      <section class="lg-card">
        <header class="lg-card-head">
          <span class="lg-card-ico lg-ico-teal"><icons name="table" class="w-5 h-5" /></span>
          <div class="min-w-0 flex-1">
            <h2 class="lg-card-title">{{ $t('Warehouse Stock') }}</h2>
            <p class="lg-card-sub print:hidden">
              {{ $t('Report Generated Date') }}: {{ $datetime(now) }} &middot;
              {{ $t('Generated By') }}: {{ ($page.props.auth && $page.props.auth.user && $page.props.auth.user.name) || 'N/A' }}
            </p>
          </div>
          <span class="lg-chip lg-chip-cyan" style="text-transform: none">{{ filteredItems.length }} {{ $t('Item(s)') }}</span>
        </header>
        <div class="lg-table-wrap">
          <table class="lg-table lg-responsive">
            <thead>
              <tr>
                <th class="text-center">{{ $t('No') }}</th>
                <th>{{ $t('Item Code') }}</th>
                <th>{{ $t('Item Name') }}</th>
                <th class="num">{{ $t('Stock Quantity') }}</th>
                <th>{{ $t('Unit') }}</th>
                <th class="num">{{ $t('Price') }}</th>
                <th class="num">{{ $t('Total Amount') }}</th>
              </tr>
            </thead>
            <tbody>
              <tr
                v-for="(item, index) in filteredItems"
                :key="item.item_id ?? index"
                class="stk-row"
                :style="{ animationDelay: Math.min(index * 25, 500) + 'ms' }"
              >
                <td :data-label="$t('No')" class="text-center" style="color: var(--lg-faint)">{{ index + 1 }}</td>
                <td :data-label="$t('Item Code')"><span class="lg-mono">{{ item.code }}</span></td>
                <td :data-label="$t('Item Name')" class="lg-main">{{ item.item_name }}</td>
                <td :data-label="$t('Stock Quantity')" class="num">{{ $number(item.quantity) }}</td>
                <td :data-label="$t('Unit')">{{ item.unit || '-' }}</td>
                <td :data-label="$t('Price')" class="num">{{ $number(item.price) }} Tsh</td>
                <td :data-label="$t('Total Amount')" class="num stk-total-cell">{{ $number(item.total) }} Tsh</td>
              </tr>
              <tr v-if="!filteredItems.length" class="lg-empty-row">
                <td class="lg-empty" colspan="7">
                  <div class="flex flex-col items-center gap-2">
                    <icons name="collection" class="w-8 h-8" />
                    <span>{{ !warehouse ? $t('Select a project / warehouse to view its stock.') : (search ? $t('No matching item found.') : $t('The warehouse is currently empty.')) }}</span>
                  </div>
                </td>
              </tr>
              <tr v-if="filteredItems.length" class="stk-foot-row">
                <td :data-label="$t('Total')" colspan="3">{{ $t('Total') }}</td>
                <td :data-label="$t('Stock Quantity')" class="num">{{ $number(filteredTotalQuantity) }} {{ $t('Item(s)') }}</td>
                <td class="stk-foot-empty"></td>
                <td class="stk-foot-empty"></td>
                <td :data-label="$t('Total Amount')" class="num stk-total-cell">{{ $number(filteredTotalValue) }} Tsh</td>
              </tr>
            </tbody>
          </table>
        </div>
      </section>
    </div>
  </admin-layout>
</template>

<script>
import AdminLayout from '@/Layouts/AdminLayout.vue';
import AutoComplete from '@/Shared/AutoComplete.vue';
import TextInput from '@/Shared/TextInput.vue';
import PageHeader from '@/Shared/Page/PageHeader.vue';
import StatTiles from '@/Shared/Page/StatTiles.vue';

export default {
  components: {
    AdminLayout,
    AutoComplete,
    TextInput,
    PageHeader,
    StatTiles,
  },

  props: {
    stocklist: Array,
    warehouses: Array,
    selectedWarehouseId: {
      type: Number,
      default: null,
    },
  },

  data() {
    return {
      warehouse: this.selectedWarehouseId || null,
      search: '',
      now: new Date(),
      animated: { items: 0, quantity: 0, value: 0 },
    };
  },

  mounted() {
    if (this.selectedWarehouseId) {
      // The server already resolved a warehouse from the URL — trust it,
      // don't override it and re-navigate (that was snapping every visit
      // back to whichever warehouse happens to be first).
      this.warehouse = this.selectedWarehouseId;
    } else if (this.warehouses && this.warehouses.length) {
      this.warehouse = this.warehouses[0].id;
      this.loadData();
    }
    this.animateStats();
  },

  watch: {
    // Re-plays the count-up whenever a warehouse switch brings in a new
    // stocklist — preserveState keeps this component instance alive across
    // that Inertia visit, so props update reactively rather than remounting.
    stocklist() {
      this.animateStats();
    },
  },

  computed: {
    statTiles() {
      return [
        { icon: 'collection', tone: 'navy', label: this.$t('Items In Stock'), value: Math.round(this.animated.items).toLocaleString() },
        { icon: 'chart-bar', tone: 'sky', label: this.$t('Total Quantity'), value: this.$number(this.animated.quantity) },
        { icon: 'cash', tone: 'emerald', label: this.$t('Total Stock Value'), value: this.$number(this.animated.value) + ' Tsh' },
      ];
    },
    filteredItems() {
      const query = this.search.trim().toLowerCase();
      if (!query) {
        return this.stocklist;
      }
      return this.stocklist.filter(row => (row.item_name ?? '').toLowerCase().includes(query) || (row.code ?? '').toLowerCase().includes(query));
    },
    totalQuantity() {
      return this.stocklist.reduce((sum, row) => sum + Number(row.quantity || 0), 0);
    },
    totalValue() {
      return this.stocklist.reduce((sum, row) => sum + Number(row.total || 0), 0);
    },
    filteredTotalQuantity() {
      return this.filteredItems.reduce((sum, row) => sum + Number(row.quantity || 0), 0);
    },
    filteredTotalValue() {
      return this.filteredItems.reduce((sum, row) => sum + Number(row.total || 0), 0);
    },
    selectedWarehouseName() {
      const match = this.warehouses?.find(item => item.id === this.warehouse);
      return match ? match.name : null;
    },
  },

  methods: {
    onWarehouseChange() {
      this.loadData();
    },
    loadData() {
      this.$inertia.visit(window.location.pathname, {
        method: 'get',
        data: { warehouseId: this.warehouse },
        preserveState: true,
      });
    },
    reportUrl(output) {
      return this.route('reports.warehousestock', { warehouseId: this.warehouse, output });
    },
    openPrint() {
      if (!this.warehouse) return;
      window.open(this.reportUrl('print'), '_blank');
    },
    downloadPdf() {
      if (!this.warehouse) return;
      window.open(this.reportUrl('pdf'), '_blank');
    },
    // Delta-time-independent ease-out count-up, same shape as the app's own
    // boot-loader easing in app.blade.php — smooth regardless of refresh rate.
    animateNumber(key, target, duration = 900) {
      const start = this.animated[key] || 0;
      const startTime = performance.now();
      const step = now => {
        const progress = Math.min((now - startTime) / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        this.animated[key] = start + (target - start) * eased;
        if (progress < 1) {
          requestAnimationFrame(step);
        } else {
          this.animated[key] = target;
        }
      };
      requestAnimationFrame(step);
    },
    animateStats() {
      this.animateNumber('items', this.stocklist.length);
      this.animateNumber('quantity', this.totalQuantity);
      this.animateNumber('value', this.totalValue);
    },
  },
};
</script>

